"""Labeled questions for training and testing the question classifier.

Train: questions generated by Claude (scripts/generate_classifier_data.py), balanced
across the six categories. Test: the 81 hand-written retrieval eval questions (which
already carry a category) plus 24 hand-written off-topic ones, since the eval set has
none. Training on generated text and testing on human-written text also shows whether
the classifier copes with phrasing it wasn't trained on.
"""

import json
from dataclasses import dataclass
from pathlib import Path
from typing import get_args

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

from sklearn_assistant.agent.prompts import Category
from sklearn_assistant.config import CLASSIFIER_TRAIN_PATH, EVAL_QUESTIONS_PATH, OFF_TOPIC_TEST_PATH

# The label set, in a fixed order (used for reports and confusion matrices).
# get_args turns Literal["howto", "concept", ...] into ("howto", "concept", ...), so the
# labels can't drift from the ones the LLM classifier is allowed to return.
CATEGORIES: list[str] = list(get_args(Category))
# A training question this similar (TF-IDF cosine) to a test question is dropped, so
# the test score isn't inflated by near-copies of test questions in the training data.
LEAKAGE_THRESHOLD = 0.8


@dataclass
class LabeledQuestion:
    question: str
    category: str


def load_jsonl(path: Path) -> list[LabeledQuestion]:
    """Read question/category pairs, ignoring any other fields (e.g. the eval set's labels)."""
    with open(path, encoding="utf-8") as f:
        rows = [json.loads(line) for line in f if line.strip()]
    return [LabeledQuestion(r["question"], r["category"]) for r in rows]


def load_train() -> list[LabeledQuestion]:
    return load_jsonl(CLASSIFIER_TRAIN_PATH)


def load_test() -> list[LabeledQuestion]:
    return load_jsonl(EVAL_QUESTIONS_PATH) + load_jsonl(OFF_TOPIC_TEST_PATH)


def drop_leakage(train: list[dict], test_questions: list[str]) -> list[dict]:
    """Remove training questions that are near-duplicates of a test question."""
    vectorizer = TfidfVectorizer().fit([t["question"] for t in train] + test_questions)
    sims = cosine_similarity(vectorizer.transform([t["question"] for t in train]),
                             vectorizer.transform(test_questions))
    # For each training question, its highest similarity to any test question.
    return [t for t, s in zip(train, sims.max(axis=1)) if s < LEAKAGE_THRESHOLD]
